-- Garante no próprio banco que um material não tenha duas cautelas abertas.
CREATE UNIQUE INDEX IF NOT EXISTS materiais_cautelas_aberta_uidx
    ON public.materiais_cautelas (material_id)
    WHERE devolvido_em IS NULL;
CREATE INDEX IF NOT EXISTS materiais_cautelas_material_data_idx
    ON public.materiais_cautelas (material_id, entregue_em DESC, id DESC);
CREATE INDEX IF NOT EXISTS materiais_cautelas_setor_data_idx
    ON public.materiais_cautelas (setor, entregue_em DESC, id DESC);
CREATE INDEX IF NOT EXISTS materiais_cautelas_responsavel_data_idx
    ON public.materiais_cautelas (responsavel_id, entregue_em DESC, id DESC);
CREATE INDEX IF NOT EXISTS materiais_cautelas_viatura_idx
    ON public.materiais_cautelas (viatura_id)
    WHERE viatura_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS materiais_cautelas_grupo_entrega_idx
    ON public.materiais_cautelas (grupo_entrega)
    WHERE grupo_entrega IS NOT NULL;

-- Abrangência de subunidades representadas por cada policial de serviço de dia.
CREATE TABLE IF NOT EXISTS public.usuarios_materiais_setores (
    usuario_id INTEGER NOT NULL REFERENCES public.usuarios(id) ON DELETE CASCADE,
    setor TEXT NOT NULL CHECK (setor IN ('EM', 'CTT', '1° CIA', '2° CIA', '3° CIA', '4° CIA')),
    concedido_por TEXT NOT NULL,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (usuario_id, setor)
);
CREATE INDEX IF NOT EXISTS usuarios_materiais_setores_setor_idx
    ON public.usuarios_materiais_setores (setor, usuario_id);

-- Fotografias de conferência registradas no encerramento do serviço de dia.
CREATE TABLE IF NOT EXISTS public.materiais_encerramentos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operador_id INTEGER REFERENCES public.usuarios(id) ON DELETE SET NULL,
    operador_nome TEXT NOT NULL,
    operador_re TEXT NOT NULL,
    setores TEXT[] NOT NULL,
    inicio_periodo TIMESTAMPTZ NOT NULL,
    encerrado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    materiais_entregues INTEGER NOT NULL DEFAULT 0 CHECK (materiais_entregues >= 0),
    materiais_devolvidos INTEGER NOT NULL DEFAULT 0 CHECK (materiais_devolvidos >= 0),
    materiais_pendentes INTEGER NOT NULL DEFAULT 0 CHECK (materiais_pendentes >= 0),
    viaturas_vinculadas INTEGER NOT NULL DEFAULT 0 CHECK (viaturas_vinculadas >= 0),
    pendencias JSONB NOT NULL DEFAULT '[]'::jsonb,
    observacao TEXT,
    CHECK (cardinality(setores) BETWEEN 1 AND 6),
    CHECK (jsonb_typeof(pendencias) = 'array'),
    CONSTRAINT materiais_encerramentos_observacao_limite
        CHECK (observacao IS NULL OR char_length(observacao) <= 2000)
);
ALTER TABLE public.materiais_encerramentos
    ADD COLUMN IF NOT EXISTS observacao TEXT;
ALTER TABLE public.materiais_encerramentos
    DROP CONSTRAINT IF EXISTS materiais_encerramentos_observacao_limite;
ALTER TABLE public.materiais_encerramentos
    ADD CONSTRAINT materiais_encerramentos_observacao_limite
    CHECK (observacao IS NULL OR char_length(observacao) <= 2000);
CREATE INDEX IF NOT EXISTS materiais_encerramentos_operador_data_idx
    ON public.materiais_encerramentos (operador_id, encerrado_em DESC);

