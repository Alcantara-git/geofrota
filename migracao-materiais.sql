-- Módulo de cautela de materiais do GEOFROTA.
-- Estrutura aditiva e idempotente: não altera os dados de viaturas ou usuários.

CREATE TABLE IF NOT EXISTS public.materiais_listas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT NOT NULL CHECK (char_length(btrim(nome)) BETWEEN 1 AND 80),
    setor TEXT NOT NULL CHECK (setor IN ('EM', 'CTT', '1° CIA', '2° CIA', '3° CIA', '4° CIA')),
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    criado_por TEXT NOT NULL,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS materiais_listas_setor_nome_uidx
    ON public.materiais_listas (setor, LOWER(BTRIM(nome)));
CREATE INDEX IF NOT EXISTS materiais_listas_setor_ativo_idx
    ON public.materiais_listas (setor, ativo, nome);

CREATE TABLE IF NOT EXISTS public.materiais (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lista_id BIGINT NOT NULL REFERENCES public.materiais_listas(id) ON DELETE RESTRICT,
    nome TEXT NOT NULL CHECK (char_length(btrim(nome)) BETWEEN 1 AND 120),
    numero TEXT,
    status TEXT NOT NULL DEFAULT 'disponivel'
        CHECK (status IN ('disponivel', 'em_uso', 'manutencao')),
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    observacoes TEXT NOT NULL DEFAULT '' CHECK (char_length(observacoes) <= 1000),
    criado_por TEXT NOT NULL,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (numero IS NULL OR char_length(btrim(numero)) BETWEEN 1 AND 80)
);

CREATE UNIQUE INDEX IF NOT EXISTS materiais_lista_numero_uidx
    ON public.materiais (lista_id, LOWER(BTRIM(numero)))
    WHERE numero IS NOT NULL AND BTRIM(numero) <> '';
CREATE INDEX IF NOT EXISTS materiais_lista_status_idx
    ON public.materiais (lista_id, ativo, status, nome);

CREATE TABLE IF NOT EXISTS public.materiais_cautelas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    material_id BIGINT NOT NULL REFERENCES public.materiais(id) ON DELETE RESTRICT,
    responsavel_id INTEGER REFERENCES public.usuarios(id) ON DELETE SET NULL,
    responsavel_nome TEXT NOT NULL,
    responsavel_re TEXT NOT NULL,
    responsavel_setor TEXT,
    viatura_id INTEGER REFERENCES public.viaturas(id) ON DELETE SET NULL,
    viatura_prefixo TEXT,
    viatura_placa TEXT,
    viatura_modelo TEXT,
    lista_nome TEXT NOT NULL,
    material_nome TEXT NOT NULL,
    material_numero TEXT,
    setor TEXT NOT NULL,
    entregue_por TEXT NOT NULL,
    entregue_por_re TEXT,
    entregue_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    observacao_entrega TEXT NOT NULL DEFAULT '' CHECK (char_length(observacao_entrega) <= 1000),
    devolvido_em TIMESTAMPTZ,
    devolvido_por TEXT,
    devolvido_por_re TEXT,
    observacao_devolucao TEXT NOT NULL DEFAULT '' CHECK (char_length(observacao_devolucao) <= 1000),
    CHECK (devolvido_em IS NULL OR devolvido_em >= entregue_em)
);

